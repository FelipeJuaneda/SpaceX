/** "1 day, 2 hours, 0 minutes" with the right plurals, for the spoken countdown. */
const span = (d: number, h: number, m: number, units: [string, string][]) =>
  [d, h, m]
    .map((v, i) => (i === 0 && !v ? null : `${v} ${units[i]![v === 1 ? 0 : 1]}`))
    .filter(Boolean)
    .join(", ");
